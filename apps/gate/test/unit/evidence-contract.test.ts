import { createHash } from "node:crypto";
import { describe, expect, it } from "bun:test";
import {
  EVIDENCE_ACTION_CONTRACT_HASH_META_KEY,
  EVIDENCE_ACTION_CONTRACT_META_KEY,
  EVIDENCE_CONTRACT_HASH_META_KEY,
  EVIDENCE_PACK_HASH_META_KEY,
  evidenceActionContractHash,
} from "../../src/mcp/evidence-contract.ts";

function stable(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(stable).join(",")}]`;
  if (value !== null && typeof value === "object") {
    return `{${Object.entries(value as Record<string, unknown>)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, item]) => `${JSON.stringify(key)}:${stable(item)}`)
      .join(",")}}`;
  }
  return JSON.stringify(value) ?? "null";
}

const hash = (character: string) => character.repeat(64);

function contract(argsHash: string) {
  return {
    schemaVersion: "v1",
    action: { tool: "write_order", argsHash },
    evidence: {
      packId: hash("a"),
      retrievedAt: "2026-08-05T12:00:00.000Z",
      items: [
        {
          evidenceId: hash("e"),
          snapshotHash: hash("b"),
          contentHash: hash("c"),
          version: "1",
          modifiedAt: "2026-08-05T11:00:00.000Z",
        },
      ],
    },
  };
}

describe("Evidence-Bound Action Contract validation", () => {
  it("rejects a contract if the supplied action arguments differ", () => {
    const args = { id: 1 };
    const raw = stable(
      contract("6b86b273ff34fce19d6b804eff5a3f5745c1d0e0c7f4c1a3f0e59b68a5e5b5ac"),
    );
    const meta = {
      [EVIDENCE_ACTION_CONTRACT_META_KEY]: raw,
      [EVIDENCE_ACTION_CONTRACT_HASH_META_KEY]: "0".repeat(64),
    };
    expect(() => evidenceActionContractHash(meta, "write_order", args)).toThrow(
      "arguments do not match",
    );
  });

  it("accepts a canonical contract when the declared digest is omitted", () => {
    const args = { id: 1 };
    // The hash is intentionally generated by the same canonical serializer used by the protocol.
    const argsHash = "037c9214eef74cc3887f3a4f085b4e17d76280dafd273b0ee160c09c4ba1cfd4";
    const raw = stable(contract(argsHash));
    expect(
      evidenceActionContractHash({ [EVIDENCE_ACTION_CONTRACT_META_KEY]: raw }, "write_order", args),
    ).toHaveLength(64);
  });
});

it("rejects contracts that attempt to carry raw evidence content", () => {
  const args = { id: 1 };
  const argsHash = "037c9214eef74cc3887f3a4f085b4e17d76280dafd273b0ee160c09c4ba1cfd4";
  const invalid = contract(argsHash);
  const evidence = invalid.evidence.items[0];
  if (evidence === undefined) throw new Error("missing evidence fixture");
  (evidence as Record<string, unknown>).content = "untrusted source text";
  expect(() =>
    evidenceActionContractHash(
      { [EVIDENCE_ACTION_CONTRACT_META_KEY]: stable(invalid) },
      "write_order",
      args,
    ),
  ).toThrow("unsupported field 'content'");
});

describe("Evidence contract hash wire aliases", () => {
  const args = { id: 1 };
  const argsHash = "037c9214eef74cc3887f3a4f085b4e17d76280dafd273b0ee160c09c4ba1cfd4";

  it("canonicalizes equal mixed-case aliases to lowercase", () => {
    const raw = stable(contract(argsHash));
    const computed = createHash("sha256").update(raw).digest("hex");
    expect(
      evidenceActionContractHash(
        {
          [EVIDENCE_ACTION_CONTRACT_META_KEY]: raw,
          [EVIDENCE_ACTION_CONTRACT_HASH_META_KEY]: computed.toUpperCase(),
          [EVIDENCE_CONTRACT_HASH_META_KEY]: computed,
          [EVIDENCE_PACK_HASH_META_KEY]: hash("A"),
        },
        "write_order",
        args,
      ),
    ).toBe(computed);
  });

  it("rejects conflicting action-contract hash aliases", () => {
    const raw = stable(contract(argsHash));
    expect(() =>
      evidenceActionContractHash(
        {
          [EVIDENCE_ACTION_CONTRACT_META_KEY]: raw,
          [EVIDENCE_ACTION_CONTRACT_HASH_META_KEY]: hash("b"),
          [EVIDENCE_CONTRACT_HASH_META_KEY]: hash("c"),
        },
        "write_order",
        args,
      ),
    ).toThrow("conflicts");
  });

  it("rejects response evidence-pack metadata that conflicts with the contract", () => {
    const raw = stable(contract(argsHash));
    expect(() =>
      evidenceActionContractHash(
        {
          [EVIDENCE_ACTION_CONTRACT_META_KEY]: raw,
          [EVIDENCE_PACK_HASH_META_KEY]: hash("d"),
        },
        "write_order",
        args,
      ),
    ).toThrow("Evidence pack hash does not match");
  });
});
