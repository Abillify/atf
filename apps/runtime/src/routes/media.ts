/**
 * Media route (`src/routes/media.ts`)
 *
 * Serves generated media (images/audio/video) produced by the `generate_image`
 * media tool or native image-generation models, stored transiently in the
 * {@link MediaStore}. The chat stream embeds a short markdown image pointing
 * here (`![](<base>/media/<id>.<ext>)`) instead of a megabyte-long base64
 * data-URI, which Open WebUI cannot render. See open-webui/open-webui#16976.
 *
 *   GET /v1/media/:id   — the raw bytes with the stored Content-Type, or 404
 *
 * SECURITY: although it lives under `/v1`, this endpoint is explicitly EXEMPT
 * from the API auth/rate-limit middleware (see index.ts) — a browser `<img>`
 * tag loads it without the API bearer token. The unguessable id (a v4 UUID
 * minted by the store) is therefore the capability; entries are short-lived
 * (store TTL) and there is no listing/enumeration. Only backend-generated bytes
 * are ever served. It lives under `/v1` (rather than a top-level `/media`) so
 * the reverse-proxy/router rule that already forwards `/v1/*` to the backend
 * reaches it without extra routing config.
 *
 * No `any` at module boundaries.
 */

import { Hono } from "hono";
import type { MediaStore } from "../graph/media-store.js";

export function createMediaRouter(store: MediaStore): Hono {
  const router = new Hono();

  router.get("/v1/media/:id", (ctx) => {
    // The extension in the URL is cosmetic — strip it to recover the store id.
    const raw = ctx.req.param("id");
    const id = raw.split(".")[0] ?? raw;

    const media = store.get(id);
    if (media === undefined) {
      return ctx.json(
        {
          error: {
            message: "Media not found or expired.",
            type: "not_found",
          },
        },
        404,
      );
    }

    // Return a standard Response so the Uint8Array is sent verbatim (avoids the
    // Buffer-pool byteOffset pitfall of unwrapping `.buffer`).
    const bytes = media.data.slice().buffer;
    return new Response(bytes, {
      status: 200,
      headers: {
        "Content-Type": media.mediaType,
        // Immutable content addressed by an unguessable id — safe to cache in
        // the browser. `private` keeps it out of shared/CDN caches since the
        // URL is a capability. The store TTL bounds server-side lifetime.
        "Cache-Control": "private, max-age=3600, immutable",
        "X-Content-Type-Options": "nosniff",
      },
    });
  });

  return router;
}
