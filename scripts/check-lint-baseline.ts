/**
 * Lint regression gate.
 *
 *   bun run lint:baseline           # fail if lint findings grew past the baseline
 *   bun run lint:baseline -- --update  # record the current counts as the new baseline
 *
 * The repository carries a real stock of pre-existing Biome findings, mostly
 * `lint/style/noNonNullAssertion`. Demanding zero would block every pull request behind an
 * unrelated cleanup, and disabling the linter would let new problems in unnoticed. This gate
 * takes the middle path: existing findings are tolerated at their recorded count, and any
 * increase fails. The counts are meant to be ratcheted down over time, never up.
 *
 * The formatter is deliberately not part of this gate. Formatting differences across the tree
 * are extensive and reformatting them in one commit would destroy `git blame` for little
 * benefit. Format the files you touch (`bunx biome format --write <path>`) and leave the rest.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";

const root = process.cwd();
const baselinePath = resolve(root, ".biome-baseline.json");
const update = process.argv.includes("--update");

/**
 * Must stay above the total number of diagnostics, otherwise Biome truncates its report and the
 * counts silently drift downwards, which would make the gate pass on a regression.
 */
const MAX_DIAGNOSTICS = 10_000;

interface Baseline {
	errors: number;
	warnings: number;
	note?: string;
}

const result = spawnSync(
	resolve(root, "node_modules", ".bin", "biome"),
	[
		"lint",
		`--max-diagnostics=${MAX_DIAGNOSTICS}`,
		"--reporter=json",
		"--no-errors-on-unmatched",
	],
	{ encoding: "utf-8", maxBuffer: 256 * 1024 * 1024 },
);

if (!result.stdout) {
	console.error("Biome produced no report.");
	console.error(result.stderr);
	process.exit(1);
}

let report: { diagnostics: { severity: string }[] };
try {
	report = JSON.parse(result.stdout) as typeof report;
} catch (error) {
	console.error(`Could not parse the Biome report: ${(error as Error).message}`);
	console.error(result.stderr);
	process.exit(1);
}

let errors = 0;
let warnings = 0;
for (const diagnostic of report.diagnostics) {
	if (diagnostic.severity === "error") errors++;
	else if (diagnostic.severity === "warning") warnings++;
}

if (errors + warnings >= MAX_DIAGNOSTICS) {
	console.error(
		`Diagnostic count (${errors + warnings}) reached the reporting cap of ${MAX_DIAGNOSTICS}; the report is truncated and the counts cannot be trusted. Raise MAX_DIAGNOSTICS in scripts/check-lint-baseline.ts.`,
	);
	process.exit(1);
}

if (update) {
	const next: Baseline = {
		errors,
		warnings,
		note: "Generated by `bun run lint:baseline -- --update`. Ratchet these numbers down, never up.",
	};
	writeFileSync(baselinePath, `${JSON.stringify(next, null, 2)}\n`);
	console.log(`Baseline updated: ${errors} errors, ${warnings} warnings.`);
	process.exit(0);
}

let baseline: Baseline;
try {
	baseline = JSON.parse(readFileSync(baselinePath, "utf-8")) as Baseline;
} catch {
	console.error(
		`Missing or unreadable ${baselinePath}. Create it with \`bun run lint:baseline -- --update\`.`,
	);
	process.exit(1);
}

console.log(
	`Biome lint: ${errors} errors, ${warnings} warnings (baseline: ${baseline.errors} errors, ${baseline.warnings} warnings).`,
);

const failures: string[] = [];
if (errors > baseline.errors) {
	failures.push(`errors increased: ${errors} > ${baseline.errors}`);
}
if (warnings > baseline.warnings) {
	failures.push(`warnings increased: ${warnings} > ${baseline.warnings}`);
}

if (failures.length > 0) {
	console.error(`\n${failures.map((line) => `  - ${line}`).join("\n")}`);
	console.error(
		"\nRun `bun run lint` to see the findings. Fix the new ones. Only update the baseline when an increase is intentional and reviewed.",
	);
	process.exit(1);
}

if (errors < baseline.errors || warnings < baseline.warnings) {
	console.log(
		"Below baseline. Run `bun run lint:baseline -- --update` to lock in the improvement.",
	);
} else {
	console.log("At baseline.");
}
